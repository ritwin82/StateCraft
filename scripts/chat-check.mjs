import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  await page.goto('http://127.0.0.1:5173');
  await page.getByLabel('Your question', { exact: true }).fill('Explain epsilon transitions in two short sentences.');
  const reply = page.waitForResponse(r => r.url().endsWith('/api/chat'), { timeout: 70000 });
  await page.getByRole('button', { name: 'Ask Ollama', exact: true }).click();
  const response = await reply;
  assert.equal(response.status(), 200, await response.text());
  const data = await response.json();
  assert.ok(data.text.length > 20);
  await page.getByRole('log').getByText(data.text, { exact: true }).waitFor();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: 'artifacts/chat-desktop.png', fullPage: true });
  let requestBody;
  await page.route('**/api/chat', async route => { requestBody = route.request().postDataJSON(); await route.fulfill({ json: { text: 'The earlier explanation describes a move without consuming input.', model: data.model } }); });
  await page.getByLabel('Your question', { exact: true }).fill('Can you give another example?');
  await page.getByRole('button', { name: 'Ask Ollama', exact: true }).click();
  await page.getByText('The earlier explanation describes a move without consuming input.', { exact: true }).waitFor();
  assert.equal(requestBody.messages.length, 3);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Fit machine to canvas' }).click();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: 'artifacts/chat-mobile.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.getByRole('button', { name: 'Clear chat', exact: true }).click();
  assert.equal(await page.getByRole('log').count(), 0);
  await page.route('**/api/chat', route => route.fulfill({ status: 503, json: { error: 'Ollama unavailable. Try again.' } }));
  await page.getByLabel('Your question', { exact: true }).fill('What is a DFA?');
  await page.getByRole('button', { name: 'Ask Ollama', exact: true }).click();
  await page.getByRole('alert').waitFor();
  assert.equal(await page.getByLabel('Your question', { exact: true }).inputValue(), 'What is a DFA?');
  await page.route('**/api/chat', async route => { await new Promise(resolve => setTimeout(resolve, 1000)); await route.fulfill({ json: { text: 'A late reply.', model: data.model } }).catch(() => {}); });
  await page.getByRole('button', { name: 'Ask Ollama', exact: true }).click();
  await page.getByRole('button', { name: 'Stop reply', exact: true }).click();
  await page.getByRole('button', { name: 'Ask Ollama', exact: true }).waitFor();
  assert.equal(await page.getByLabel('Your question', { exact: true }).inputValue(), 'What is a DFA?');
  await page.getByRole('button', { name: 'Next challenge', exact: true }).click();
  assert.equal(await page.getByRole('log').count(), 0);
  console.log(JSON.stringify({ model: data.model, liveReply: true, followUpContext: true, clearChat: true, recoverableError: true, stopReply: true, challengeReset: true, mobileOverflow: false }));
} finally { await browser.close(); }
