import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import { generateQuestion } from '../packages/engine/dist/index.js';
await mkdir('artifacts', { recursive: true });
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
const errors = [];
let latestQuestion;
await page.route('**/api/questions/next*', async route => {
  const response = await route.fetch();
  latestQuestion = await response.json();
  await route.fulfill({ response });
});
page.on('pageerror', e => errors.push(e.message));
await page.goto('http://127.0.0.1:5173');
await page.getByRole('heading', { name: 'Small states. Big understanding.' }).waitFor();
await page.evaluate(() => document.fonts.ready);
if (process.argv.includes('--capture')) await page.screenshot({ path: 'artifacts/desktop.png', fullPage: true });
await page.getByRole('button', { name: 'Check my machine', exact: true }).click();
await page.getByText('Almost. Follow this string.').waitFor();
await page.getByRole('button', { name: 'Trace counterexample' }).click();
await page.getByRole('button', { name: 'Transition', exact: true }).click();
await page.getByLabel('From state', { exact: true }).selectOption('q2');
await page.getByLabel('To state', { exact: true }).selectOption('q1');
await page.getByLabel('Transition symbol').fill('a');
await page.getByRole('button', { name: 'Save transition' }).click();
await page.getByRole('button', { name: 'Check my machine', exact: true }).click();
await page.getByText('Beautifully done.').waitFor();
await page.getByLabel('Input string').fill('aab');
await page.getByRole('button', { name: 'Run string', exact: true }).click();
for (let i = 0; i < 3; i++) await page.getByRole('button', { name: 'Next simulation step' }).click();
await page.getByText('Accepted', { exact: true }).waitFor();
await page.getByLabel('Input string').fill('aaa');
if (await page.getByText('Accepted', { exact: true }).count()) throw new Error('Stale simulation result');
await page.getByRole('button', { name: 'Open field guide' }).click();
await page.getByRole('button', { name: 'Practice studio', exact: true }).click();
await page.getByText('Beautifully done.').waitFor();
await page.getByRole('button', { name: 'My progress', exact: true }).click();
await page.getByRole('heading', { name: 'Understanding, one machine at a time.' }).waitFor();
await page.getByRole('button', { name: 'Debug the machine', exact: true }).click();
await page.getByRole('heading', { name: 'Debug the machine.' }).waitFor();
await page.getByRole('button', { name: 'Give me a hint' }).click();
await page.getByText('Verified template · sign in for Ollama hints').waitFor();
await page.getByRole('button', { name: 'Open field guide' }).click();
await page.getByRole('heading', { name: 'Make the abstract click.' }).waitFor();
const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, deviceScaleFactor: 1 });
mobile.on('pageerror', e => errors.push(e.message));
await mobile.goto('http://127.0.0.1:5173');
await mobile.getByRole('heading', { name: 'Small states. Big understanding.' }).waitFor();
await mobile.evaluate(() => document.fonts.ready);
if (process.argv.includes('--capture')) await mobile.screenshot({ path: 'artifacts/mobile.png', fullPage: true });
const overflow = await mobile.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
await mobile.getByRole('button', { name: 'Add state', exact: true }).click();
await mobile.getByRole('button', { name: 'Accepting', exact: true }).click();
// An account challenge must use the API, including after a page reload.
await page.getByRole('button', { name: 'Open account' }).click();
await page.getByLabel('Name', { exact: true }).fill('Browser Learner');
await page.getByLabel('Email', { exact: true }).fill(`browser-${Date.now()}@example.test`);
await page.getByLabel('Password', { exact: false }).fill('browser-test-password');
const nextResponse = page.waitForResponse(r => r.url().includes('/api/questions/next'));
await page.getByRole('button', { name: 'Create account', exact: true }).click();
await nextResponse;
await page.getByRole('button', { name: 'Practice studio', exact: true }).click();
await page.waitForLoadState('networkidle');
const reloadQuestion = page.waitForResponse(r => r.url().includes('/api/questions/next'));
await page.reload();
await reloadQuestion;
await page.waitForLoadState('networkidle');
const publicQuestion = latestQuestion;
if (!publicQuestion?.id) throw new Error('Authenticated reload did not load a question.');
const reference = generateQuestion(publicQuestion.topic, publicQuestion.difficulty, publicQuestion.seed, publicQuestion.id.startsWith('v2-') ? 'v2' : 'v1').reference;
const hintResponse = page.waitForResponse(r => r.url().includes('/api/hints'), { timeout: 45000 });
await page.getByRole('button', { name: 'Give me a hint' }).click();
const hint = await (await hintResponse).json();
if (hint.source !== 'ollama') throw new Error(`Expected live Ollama hint, received ${hint.source}`);
await page.locator('input[type=file]').setInputFiles({ name: 'solution.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(reference)) });
const saved = page.waitForResponse(r => r.url().endsWith('/api/attempts'));
await page.getByRole('button', { name: 'Check my machine', exact: true }).click();
const attempt = await (await saved).json();
if (!attempt.result.equivalent || attempt.attempt.score !== .85) throw new Error('Account score/persistence failed');
await page.getByText('Beautifully done.').waitFor();
await page.getByRole('button', { name: 'My progress', exact: true }).click();
await page.getByRole('cell', { name: '85%', exact: true }).waitFor();
console.log(JSON.stringify({ desktop: 'counterexample, repair, simulation, preserved navigation, progress, debug, hints, guide passed', account: 'registration, reload, live Ollama hint, score and saved attempt passed', mobile: 'render, state creation and acceptance editing passed', horizontalOverflow: overflow, browserErrors: errors }, null, 2));
await browser.close();
if (overflow || errors.length) process.exitCode = 1;
